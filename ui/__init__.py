#           （用户看到的"hosts 未被改动 / 关不掉"）；
#         · 进房间时那颗 UAC 弹窗会把桌面变暗、等用户点击（用户感知的
#           "打开联网房间卡顿"）。
#       v1.0.5 那套"加速页权限状态条 + 以管理员身份重启 + 单实例接管"
#       因此**整体删除** —— 启动即提权之后，它是多余的一层。
